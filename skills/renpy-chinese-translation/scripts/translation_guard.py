#!/usr/bin/env python3
"""
Read-only guard for Ren'Py translation files.

The hard invariant is that reference material generated by Ren'Py is not
translated or polished:
  - comment reference lines are compared against the source file
  - old "..." string keys must remain English
  - voice lines, character prefixes, nointeract suffixes, tags, and
    interpolation placeholders must be preserved
"""

from __future__ import annotations

import argparse
import ast
import re
import subprocess
import sys
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path


CHINESE_RE = re.compile(r"[\u3400-\u9fff]")
ENGLISH_RE = re.compile(r"[A-Za-z]{3,}")
TAG_RE = re.compile(r"\{[^}]*\}")
INTERPOLATION_RE = re.compile(r"\[[^\]]+\]")
LOCATION_RE = re.compile(r"^\s*#\s+game/(.*):(\d+)\s*$")
TRANSLATE_RE = re.compile(r"^\s*translate\s+\w+\s+([A-Za-z0-9_.]+|strings):\s*$")
OLD_RE = re.compile(r"^\s*old\s+(\"(?:[^\"\\]|\\.)*\")\s*$")
NEW_RE = re.compile(r"^\s*new\s+(\"(?:[^\"\\]|\\.)*\")\s*$")
DIALOGUE_RE = re.compile(
    r"^(?P<indent>\s*)"
    r"(?:(?P<who>[A-Za-z_]\w*)\s+)?"
    r"(?P<quoted>\"(?:[^\"\\]|\\.)*\")"
    r"(?P<suffix>.*)$"
)
BAD_DIALOGUE_DELIMITER_RE = re.compile(r"^\s*[A-Za-z_]\w*\s+[“”]")

RAW_NAME_RE = re.compile(
    r"\b(Haelo|Horne|Grey|Elie|Locke|Gerrard|Gerrand|Rishaan|Kayden|Gloria|"
    r"Justin|Paulo|Karen|Purgatory|Nexus|Guardian|Guardians|Trial|Trials|"
    r"Essence|Heaven|Hell|Archangel|Overlord)\b"
)

FORBIDDEN_TERMS = [
    ("haelo_wrong", re.compile(r"哈罗|哈喽")),
    ("grey_wrong", re.compile(r"格瑞|(?<!银)灰色(?!调|彩|地带|区域|天空|雾|眼|光|石|墙|布|影|云|发|烟|尘|皮|树皮|袍|线|金属|房间|地板|道路|轮廓|背景|调子|地毯|西装|外套|裤|衬衫)")),
    ("elie_wrong", re.compile(r"埃利")),
    ("nexus_wrong", re.compile(r"枢纽|灵枢|联系状态|Nexus")),
    ("essence_wrong", re.compile(r"本质")),
    ("guardian_wrong", re.compile(r"监护人")),
    ("supreme_wrong", re.compile(r"至尊主|至尊(?!存在)")),
    ("escort_wrong", re.compile(r"伴游|陪护")),
    ("trial_wrong", re.compile(r"一审|试用|审判庭|完成审判(?!过程)")),
    ("shit_wrong", re.compile(r"拉屎")),
    ("name_spacing", re.compile(r"(?:[一-鿿，。！？、；：（“][ \t]+(?:海洛|霍恩|艾利|格雷|洛克|杰拉德|瑞尚|凯登|格洛丽亚)|(?:海洛|霍恩|艾利|格雷|洛克|杰拉德|瑞尚|凯登|格洛丽亚)[ \t]+[一-鿿])")),
    ("ascii_punctuation", re.compile(r"(?<=[一-鿿])\.(?!\.)|\.{2,}|……。")),
    ("zero_width_space", re.compile("\u200b")),
]

ALLOWED_ENGLISH_PATTERNS = [
    re.compile(pattern, re.IGNORECASE)
    for pattern in [
        r"https?://\S+",
        r"\b[a-z_]+(?:\.[A-Za-z_][A-Za-z0-9_]*)+\b",
        r"\b[A-Za-z0-9_./-]+\.(?:txt|rpy|rpym|png|jpg|jpeg|webp|ogg|mp3|wav)\b",
        r"(?<![A-Za-z0-9_])(?:Shift|Alt|Ctrl|Tab|Esc|Escape)(?:\+[A-Za-z])?(?![A-Za-z0-9_])",
        r"(?<![A-Za-z0-9_])(?:Ren'?Py|MIT|GNU|LGPL|GL2|ANGLE2|GLES2|BBCode|BBcode|Markdown)(?![A-Za-z0-9_])",
        r"(?<![A-Za-z0-9_])(?:Discord|Steam|App Store|Lovense|DejaVu Sans|Opendyslexic)(?![A-Za-z0-9_])",
        r"(?<![A-Za-z0-9_])(?:Heartskip Games|Heartskip|HeartSkip|BLits)(?![A-Za-z0-9_])",
    ]
]


@dataclass(frozen=True)
class Issue:
    severity: str
    kind: str
    file: Path
    line: int
    message: str


@dataclass
class ParsedLine:
    who: str
    text: str
    suffix: str


class Guard:
    def __init__(self, root: Path, max_examples: int) -> None:
        self.root = root
        self.max_examples = max_examples
        self.issues: list[Issue] = []
        self.source_cache: dict[str, list[str] | None] = {}

    def add(self, severity: str, kind: str, file: Path, line: int, message: str) -> None:
        self.issues.append(Issue(severity, kind, file, line, message))

    def read_source(self, rel: str) -> list[str] | None:
        if rel not in self.source_cache:
            path = self.root / rel
            if path.exists():
                self.source_cache[rel] = path.read_text(encoding="utf-8").splitlines()
            else:
                self.source_cache[rel] = None
        return self.source_cache[rel]

    def scan(self, files: list[Path]) -> None:
        for file in files:
            self.scan_file(file)

    def scan_file(self, file: Path) -> None:
        try:
            lines = file.read_text(encoding="utf-8-sig").splitlines()
        except UnicodeDecodeError as exc:
            self.add("ERROR", "decode_error", file, 1, str(exc))
            return

        self.check_comment_anchors(file, lines)
        self.check_translate_blocks(file, lines)
        self.check_string_tables(file, lines)
        self.check_line_level(file, lines)

    def check_comment_anchors(self, file: Path, lines: list[str]) -> None:
        for index, line in enumerate(lines):
            loc = LOCATION_RE.match(line)
            if not loc:
                continue

            source_rel = loc.group(1)
            source_line = int(loc.group(2))
            source_lines = self.read_source(source_rel)
            if source_lines is None:
                self.add("ERROR", "missing_source", file, index + 1, f"cannot find game/{source_rel}")
                continue

            comments = self.block_reference_comments(lines, index + 1)

            for offset, comment in enumerate(comments):
                source_index = source_line - 1 + offset
                if source_index >= len(source_lines):
                    self.add("ERROR", "comment_anchor", file, index + 1, "anchor points past source file end")
                    continue

                expected = source_lines[source_index].strip()
                if comment != expected:
                    self.add(
                        "ERROR",
                        "comment_mismatch",
                        file,
                        index + 1 + offset,
                        f"comment changed; expected: {expected}",
                    )

    def block_reference_comments(self, lines: list[str], start: int) -> list[str]:
        index = start
        while index < len(lines) and (TRANSLATE_RE.match(lines[index]) or not lines[index].strip()):
            index += 1

        comments: list[str] = []
        while index < len(lines) and lines[index].lstrip().startswith("#"):
            text = lines[index].lstrip()[1:]
            if text.startswith(" "):
                text = text[1:]
            comments.append(text.rstrip())
            index += 1

        return comments

    def check_translate_blocks(self, file: Path, lines: list[str]) -> None:
        index = 0
        while index < len(lines):
            match = TRANSLATE_RE.match(lines[index])
            if not match or match.group(1) == "strings":
                index += 1
                continue

            block_start = index + 1
            index += 1

            while index < len(lines) and not lines[index].strip():
                index += 1

            comments: list[tuple[int, str]] = []
            while index < len(lines) and lines[index].lstrip().startswith("#"):
                text = lines[index].lstrip()[1:]
                if text.startswith(" "):
                    text = text[1:]
                comments.append((index + 1, text.rstrip()))
                index += 1

            code: list[tuple[int, str]] = []
            while index < len(lines) and lines[index].strip() and not TRANSLATE_RE.match(lines[index]):
                if not lines[index].lstrip().startswith("#"):
                    code.append((index + 1, lines[index].rstrip()))
                index += 1

            if comments and len(comments) != len(code):
                self.add(
                    "ERROR",
                    "block_shape",
                    file,
                    block_start,
                    f"{len(comments)} reference lines but {len(code)} translated code lines",
                )

            for (comment_line, original), (code_line, translated) in zip(comments, code):
                self.check_code_pair(file, comment_line, original, code_line, translated)

    def check_code_pair(
        self, file: Path, comment_line: int, original: str, code_line: int, translated: str
    ) -> None:
        original_stripped = original.strip()
        translated_stripped = translated.strip()

        if original_stripped.startswith("voice "):
            if translated_stripped != original_stripped:
                self.add("ERROR", "voice_changed", file, code_line, "voice line differs from reference")
            return

        original_parsed = parse_dialogue(original)
        if original_parsed is None:
            return

        translated_parsed = parse_dialogue(translated)
        if translated_parsed is None:
            self.add(
                "ERROR",
                "bad_dialogue_syntax",
                file,
                code_line,
                f"translated line does not parse as Ren'Py dialogue for reference line {comment_line}",
            )
            return

        if translated_parsed.who != original_parsed.who:
            self.add(
                "ERROR",
                "speaker_changed",
                file,
                code_line,
                f"speaker changed from {original_parsed.who or '<narrator>'} to {translated_parsed.who or '<narrator>'}",
            )

        if normalize_suffix(translated_parsed.suffix) != normalize_suffix(original_parsed.suffix):
            self.add(
                "ERROR",
                "suffix_changed",
                file,
                code_line,
                f"suffix changed from {original_parsed.suffix.strip()!r} to {translated_parsed.suffix.strip()!r}",
            )

        self.check_protected_tokens(file, code_line, original_parsed.text, translated_parsed.text)
        self.check_translation_text(file, code_line, translated_parsed.text)

    def check_string_tables(self, file: Path, lines: list[str]) -> None:
        old_text: str | None = None
        old_line = 0

        for number, line in enumerate(lines, 1):
            old_match = OLD_RE.match(line)
            if old_match:
                old_text = parse_string(old_match.group(1))
                old_line = number
                if CHINESE_RE.search(old_text):
                    self.add("ERROR", "old_changed", file, number, "old string contains Chinese text")
                continue

            new_match = NEW_RE.match(line)
            if not new_match:
                continue

            new_text = parse_string(new_match.group(1))
            if old_text is None:
                self.add("ERROR", "orphan_new", file, number, "new string has no preceding old string")
                continue

            if new_text == old_text and ENGLISH_RE.search(strip_allowed_english(scrub_protected_text(new_text))):
                self.add("ERROR", "untranslated_string", file, number, "new string is identical to old string")

            self.check_protected_tokens(file, number, old_text, new_text)
            self.check_translation_text(file, number, new_text)

            old_text = None
            old_line = 0

        if old_text is not None:
            self.add("ERROR", "missing_new", file, old_line, "old string has no matching new string")

    def check_line_level(self, file: Path, lines: list[str]) -> None:
        for number, line in enumerate(lines, 1):
            stripped = line.lstrip()
            if stripped.startswith("#"):
                if CHINESE_RE.search(stripped):
                    self.add("ERROR", "comment_chinese", file, number, "comment/reference line contains Chinese")
                continue

            if BAD_DIALOGUE_DELIMITER_RE.match(line):
                self.add("ERROR", "bad_dialogue_syntax", file, number, "dialogue uses smart quote as delimiter")

    def check_protected_tokens(self, file: Path, line: int, original: str, translated: str) -> None:
        original_tags = TAG_RE.findall(original)
        translated_tags = TAG_RE.findall(translated)
        if original_tags != translated_tags:
            self.add(
                "ERROR",
                "tag_mismatch",
                file,
                line,
                f"text tags changed from {original_tags} to {translated_tags}",
            )

        original_interpolation = INTERPOLATION_RE.findall(original)
        translated_interpolation = INTERPOLATION_RE.findall(translated)
        if original_interpolation != translated_interpolation:
            self.add(
                "ERROR",
                "interpolation_mismatch",
                file,
                line,
                f"interpolation changed from {original_interpolation} to {translated_interpolation}",
            )

    def check_translation_text(self, file: Path, line: int, text: str) -> None:
        clean = strip_allowed_english(scrub_protected_text(text))

        if ENGLISH_RE.search(clean):
            severity = "ERROR" if not CHINESE_RE.search(clean) else "WARN"
            self.add(severity, "english_left", file, line, "translated text still contains English words")

        if RAW_NAME_RE.search(clean):
            self.add("WARN", "raw_term_left", file, line, "translated text still contains raw English term/name")

        for kind, pattern in FORBIDDEN_TERMS:
            if pattern.search(clean):
                self.add("WARN", kind, file, line, f"forbidden or suspicious term matched: {pattern.pattern}")

    def print_report(self, checked_files: list[Path]) -> None:
        errors = [i for i in self.issues if i.severity == "ERROR"]
        warnings = [i for i in self.issues if i.severity == "WARN"]

        print(f"Translation guard checked {len(checked_files)} file(s).")
        print(f"Errors: {len(errors)}  Warnings: {len(warnings)}")

        if not self.issues:
            print("No guard issues found.")
            return

        by_kind = Counter((i.severity, i.kind) for i in self.issues)
        print("\nCounts:")
        for (severity, kind), count in sorted(by_kind.items()):
            print(f"  {severity:<5} {kind:<24} {count}")

        grouped: dict[tuple[str, str], list[Issue]] = defaultdict(list)
        for issue in self.issues:
            grouped[(issue.severity, issue.kind)].append(issue)

        print("\nExamples:")
        for key in sorted(grouped):
            severity, kind = key
            print(f"\n[{severity} {kind}]")
            for issue in grouped[key][: self.max_examples]:
                path = issue.file if issue.file.is_absolute() else issue.file
                print(f"  {path}:{issue.line}: {issue.message}")


def parse_dialogue(line: str) -> ParsedLine | None:
    match = DIALOGUE_RE.match(line)
    if not match:
        return None

    quoted = match.group("quoted")
    try:
        text = parse_string(quoted)
    except ValueError:
        return None

    return ParsedLine(
        who=match.group("who") or "",
        text=text,
        suffix=match.group("suffix") or "",
    )


def parse_string(value: str) -> str:
    try:
        parsed = ast.literal_eval(value)
    except Exception as exc:
        raise ValueError(str(exc)) from exc
    if not isinstance(parsed, str):
        raise ValueError("string literal did not evaluate to str")
    return parsed


def normalize_suffix(value: str) -> str:
    return " ".join(value.strip().split())


def scrub_protected_text(text: str) -> str:
    text = TAG_RE.sub("", text)
    text = INTERPOLATION_RE.sub("", text)
    text = re.sub(r"gui/[A-Za-z0-9_./-]+", "", text)
    text = re.sub(r"__TAG\d+__", "", text)
    return text


def strip_allowed_english(text: str) -> str:
    for pattern in ALLOWED_ENGLISH_PATTERNS:
        text = pattern.sub("", text)
    return text


def collect_files(paths: list[str]) -> list[Path]:
    if not paths:
        paths = ["tl/schinese"]

    files: list[Path] = []
    for raw in paths:
        path = Path(raw)
        if path.is_dir():
            files.extend(sorted(path.rglob("*.rpy")))
        elif path.is_file():
            files.append(path)
        else:
            print(f"warning: path not found: {raw}", file=sys.stderr)

    return sorted(dict.fromkeys(files))


def run_renpy_count(root: Path, sdk: str, language: str) -> int:
    command = [str(Path(sdk) / "renpy.sh"), str(root), "translate", language, "--count"]
    result = subprocess.run(command, cwd=root, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    print("\nRen'Py translate --count:")
    print(result.stdout.rstrip())
    return result.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Audit Ren'Py schinese translation files without modifying them.")
    parser.add_argument("paths", nargs="*", help="Files or directories to audit. Defaults to tl/schinese.")
    parser.add_argument("--root", default=".", help="Game root directory. Defaults to current directory.")
    parser.add_argument("--max-examples", type=int, default=6, help="Maximum examples to print per issue kind.")
    parser.add_argument("--warnings-as-errors", action="store_true", help="Exit non-zero when warnings are present.")
    parser.add_argument("--renpy-sdk", help="Optional Ren'Py SDK directory for translate --count syntax checking.")
    parser.add_argument("--language", default="schinese", help="Ren'Py language name. Defaults to schinese.")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    files = collect_files(args.paths)
    guard = Guard(root=root, max_examples=args.max_examples)
    guard.scan(files)
    guard.print_report(files)

    exit_code = 0
    if any(i.severity == "ERROR" for i in guard.issues):
        exit_code = 1
    if args.warnings_as_errors and any(i.severity == "WARN" for i in guard.issues):
        exit_code = 1

    if args.renpy_sdk:
        renpy_code = run_renpy_count(root, args.renpy_sdk, args.language)
        if renpy_code != 0:
            exit_code = renpy_code

    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
